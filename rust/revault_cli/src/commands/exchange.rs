use super::context::{cli_error, vault_password_without_open, CliResult};
use clap::{Arg, ArgAction, ArgMatches, Command};
use revault_vault_api::{
    contact_exchange, default_vault_path, ComparisonChannel, ContactExchangeCommand as Operation,
    ContactExchangeStatus, SecretString,
};
use std::io::{self, IsTerminal, Write};
use std::time::{SystemTime, UNIX_EPOCH};

pub(super) fn commands() -> Vec<Command> {
    let profile = || {
        Arg::new("profile")
            .long("profile")
            .required(true)
            .help("The one local profile whose encryption and signing keys will be shared.")
    };
    let id = || {
        Arg::new("id")
            .required(true)
            .help("Exchange ID shown by exchanges.")
    };
    vec![
        Command::new("exchange").about("Invite someone to a reciprocal public-key exchange.")
            .arg(Arg::new("email").required(true))
            .arg(profile())
            .arg(Arg::new("key-server").long("key-server").required(true).help("HTTPS invitation relay origin."))
            .arg(Arg::new("ttl-hours").long("ttl-hours").default_value("24")
                .value_parser(clap::value_parser!(u64).range(1..=168))),
        Command::new("accept").about("Accept an invitation and return your selected profile's keys.")
            .arg(Arg::new("invitation").required(true).help("Invitation URL generated by exchange."))
            .arg(profile()),
        Command::new("exchanges").about("Fetch replies and show local exchange/verification status.")
            .arg(Arg::new("offline").long("offline").action(ArgAction::SetTrue)),
        Command::new("verify").about("Compare one full shared fingerprint and save both contact keys.")
            .arg(id()).arg(Arg::new("name").required(true))
            .arg(Arg::new("fingerprint").long("fingerprint")
                .help("Full shared fingerprint obtained through an independently trusted channel."))
            .arg(Arg::new("channel").long("channel")
                .value_parser(["in-person", "known-phone-call", "trusted-messenger"])
                .help("Independent channel used to compare both identities and the full fingerprint.")),
        Command::new("cancel-exchange").about("Cancel an invitation you created before acceptance.").arg(id()),
        Command::new("verify-author").about("Authenticate a lockbox against a saved contact signing key.")
            .arg(Arg::new("name").required(true)).arg(Arg::new("lockbox").required(true)),
        Command::new("forget-exchange").about("Remove local exchange state; retain any verified contact.").arg(id()),
    ]
}

fn value<'a>(args: &'a ArgMatches, name: &str) -> &'a str {
    args.get_one::<String>(name)
        .map(String::as_str)
        .unwrap_or_default()
}

fn execute(password: &SecretString, operation: Operation) -> CliResult<Vec<ContactExchangeStatus>> {
    Ok(contact_exchange(
        &default_vault_path()?,
        password,
        operation,
    )?)
}

pub(super) fn run(command: &str, args: &ArgMatches) -> CliResult<()> {
    let password = vault_password_without_open()?;
    let operation = match command {
        "exchange" => Operation::Invite {
            relay: value(args, "key-server").to_owned(),
            profile: value(args, "profile").to_owned(),
            recipient_email: value(args, "email").to_owned(),
            ttl_hours: args.get_one::<u64>("ttl-hours").copied().unwrap_or(24) as u32,
        },
        "accept" => Operation::Accept {
            invitation: value(args, "invitation").to_owned(),
            profile: value(args, "profile").to_owned(),
        },
        "exchanges" => Operation::List {
            offline: args.get_flag("offline"),
        },
        "verify" => return verify(&password, args),
        "cancel-exchange" => Operation::Cancel {
            id: value(args, "id").to_owned(),
        },
        "forget-exchange" => Operation::Forget {
            id: value(args, "id").to_owned(),
        },
        "verify-author" => Operation::VerifyAuthor {
            contact_name: value(args, "name").to_owned(),
            lockbox_path: value(args, "lockbox").to_owned(),
        },
        _ => return Err(cli_error("unknown exchange command")),
    };
    let statuses = execute(&password, operation)?;
    let pending = statuses.iter().any(|status| status.relay_pending);
    for status in statuses {
        show(&status);
    }
    match command {
        "exchange" | "accept" if pending => return Err(cli_error("exchange saved locally; relay delivery pending; retry with vault contacts exchanges")),
        "exchange" => println!("Send the invitation to the intended recipient. Compare identities and the full shared fingerprint through another trusted channel after acceptance."),
        "cancel-exchange" => println!("cancelled=yes"),
        "forget-exchange" => println!("forgotten=yes"),
        "verify-author" => println!("author={}\nverified=yes",value(args,"name")),
        _ => (),
    }
    Ok(())
}

fn verify(password: &SecretString, args: &ArgMatches) -> CliResult<()> {
    let id = value(args, "id");
    let mut status = execute(password, Operation::List { offline: true })?
        .into_iter()
        .find(|status| status.id == id)
        .ok_or_else(|| cli_error("unknown exchange ID"))?;
    if !status.accepted {
        status = execute(password, Operation::List { offline: false })?
            .into_iter()
            .find(|status| status.id == id)
            .ok_or_else(|| cli_error("exchange was removed"))?;
    }
    show(&status);
    if !status.accepted {
        return Err(cli_error("waiting for reciprocal acceptance"));
    }
    let interactive = io::stdin().is_terminal();
    // The shared API has returned: no Vault handle spans either prompt.
    let channel = if let Some(channel) = args.get_one::<String>("channel") {
        channel.clone()
    } else if interactive {
        prompt("Comparison channel (in-person / known-phone-call / trusted-messenger): ")?
    } else {
        return Err(cli_error("--channel is required when not interactive"));
    };
    let channel = match channel.as_str() {
        "in-person" => ComparisonChannel::InPerson,
        "known-phone-call" => ComparisonChannel::KnownPhoneCall,
        "trusted-messenger" => ComparisonChannel::TrustedMessenger,
        _ => {
            return Err(cli_error(
                "an independently trusted comparison channel is required",
            ))
        }
    };
    let fingerprint = if let Some(fingerprint) = args.get_one::<String>("fingerprint") {
        fingerprint.clone()
    } else if interactive {
        prompt("Enter the other person's full shared fingerprint after checking both identities: ")?
    } else {
        return Err(cli_error("--fingerprint is required when not interactive"));
    };
    let results = execute(
        password,
        Operation::Verify {
            id: id.to_owned(),
            contact_name: value(args, "name").to_owned(),
            fingerprint,
            channel,
        },
    )?;
    println!("contact={}\nverified=yes", value(args, "name"));
    if results.iter().any(|status| status.relay_pending) {
        eprintln!(
            "Contact saved; relay acknowledgement pending. Retry with vault contacts exchanges."
        );
    }
    Ok(())
}

fn show(status: &ContactExchangeStatus) {
    println!(
        "invitation={}\nexpires_at_unix_ms={}\nexchange={}\nfrom={}\nto={}",
        status.invitation,
        status.expires_ms,
        status.id,
        status.inviter_email,
        status.recipient_email
    );
    if status.accepted {
        println!("verification={}", status.fingerprint);
    }
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis();
    println!(
        "state={}",
        if status.verified {
            "verified"
        } else if status.accepted {
            "verification-needed"
        } else if now >= u128::from(status.expires_ms) {
            "expired"
        } else {
            "awaiting-acceptance"
        }
    );
    if status.relay_pending {
        eprintln!("Exchange {}: relay delivery pending", status.id);
    }
}

fn prompt(message: &str) -> CliResult<String> {
    print!("{message}");
    io::stdout().flush()?;
    let mut value = String::new();
    io::stdin().read_line(&mut value)?;
    Ok(value.trim().to_owned())
}
